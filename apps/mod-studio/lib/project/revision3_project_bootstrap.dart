void _requireProjectId(String value) {
  if (value.length != 32 ||
      !_projectIdPattern.hasMatch(value) ||
      value == '00000000000000000000000000000000') {
    throw const FormatException(
      'ProjectId must be one non-zero lowercase 128-bit identifier',
    );
  }
}

void _requireMetadata(String value, int maxBytes, String context) {
  if (value.isEmpty || value.trim() != value) {
    throw FormatException('$context must be non-empty and trimmed');
  }
  _boundedUtf8Length(value, maxBytes, context);
  for (final rune in value.runes) {
    if (rune < 0x20 || (rune >= 0x7f && rune <= 0x9f)) {
      throw FormatException('$context contains a control character');
    }
  }
}

List<String> _canonicalLocales(Iterable<String> values) {
  final locales = <String>[];
  final seen = <String>{};
  for (final value in values) {
    if (locales.length >= Revision3ProjectBootstrap.maxAuthoringLocales) {
      throw const FormatException(
        'authoring locale count exceeds its 64-entry limit',
      );
    }
    _requireCanonicalLocale(value);
    if (!seen.add(value)) {
      throw FormatException('duplicate authoring locale: $value');
    }
    locales.add(value);
  }
  locales.sort();
  return List<String>.unmodifiable(locales);
}

Revision3ProjectBootstrapTarget _validatedTarget(
  AuthoringStoryCatalogGeneration generation,
) {
  final executable = generation.executable;
  if (generation.edition.isEmpty ||
      generation.edition.trim() != generation.edition ||
      executable.byteLength <= 0 ||
      executable.byteLength > 0x7fffffffffffffff ||
      executable.sha256.length != 64 ||
      !_sha256Pattern.hasMatch(executable.sha256) ||
      executable.sha256 == _zeroSha256) {
    throw const FormatException(
      'Story catalog generation has an invalid executable seal',
    );
  }
  final supported = _supportedStoryGenerations.any(
    (candidate) =>
        generation.edition == candidate.edition &&
        executable.byteLength == candidate.executableByteLength &&
        executable.sha256 == candidate.executableSha256 &&
        generation.shippingCache.byteLength ==
            candidate.shippingCacheByteLength &&
        generation.shippingCache.sha256 == candidate.shippingCacheSha256 &&
        generation.bindsCache.byteLength == candidate.bindsCacheByteLength &&
        generation.bindsCache.sha256 == candidate.bindsCacheSha256,
  );
  if (!supported) {
    throw const FormatException(
      'Story catalog generation is not an exact supported generation triple',
    );
  }
  return Revision3ProjectBootstrapTarget._(
    edition: generation.edition,
    executableByteLength: executable.byteLength,
    executableSha256: executable.sha256,
  );
}

void _requireCanonicalLocale(String value) {
  if (value.isEmpty || value.length > 35 || !value.codeUnits.every(_isAscii)) {
    throw FormatException('authoring locale is not bounded ASCII: $value');
  }
  final segments = value.split('-');
  final language = segments.first;
  if (language.length < 2 || language.length > 8 || !_allAsciiLower(language)) {
    throw FormatException('authoring locale has an invalid language: $value');
  }
  final canonical = StringBuffer(language);
  for (var index = 1; index < segments.length; index++) {
    final segment = segments[index];
    if (segment.isEmpty ||
        segment.length > 8 ||
        !_allAsciiAlphanumeric(segment)) {
      throw FormatException('authoring locale has an invalid segment: $value');
    }
    canonical.write('-');
    if (segment.length == 4 && _allAsciiAlphabetic(segment)) {
      canonical.write(
        '${segment[0].toUpperCase()}${segment.substring(1).toLowerCase()}',
      );
    } else if (segment.length == 2 && _allAsciiAlphabetic(segment)) {
      canonical.write(segment.toUpperCase());
    } else {
      canonical.write(segment.toLowerCase());
    }
  }
  if (canonical.toString() != value) {
    throw FormatException('authoring locale is not canonical: $value');
  }
}

bool _isAscii(int unit) => unit <= 0x7f;

bool _allAsciiLower(String value) =>
    value.codeUnits.every((unit) => unit >= 0x61 && unit <= 0x7a);

bool _allAsciiAlphabetic(String value) => value.codeUnits.every(
  (unit) => (unit >= 0x41 && unit <= 0x5a) || (unit >= 0x61 && unit <= 0x7a),
);

bool _allAsciiAlphanumeric(String value) => value.codeUnits.every(
  (unit) =>
      (unit >= 0x30 && unit <= 0x39) ||
      (unit >= 0x41 && unit <= 0x5a) ||
      (unit >= 0x61 && unit <= 0x7a),
);

int _boundedUtf8Length(String value, int maxBytes, String context) {
  var length = 0;
  for (var index = 0; index < value.length; index++) {
    final unit = value.codeUnitAt(index);
    final int width;
    if (unit <= 0x7f) {
      width = 1;
    } else if (unit <= 0x7ff) {
      width = 2;
    } else if (unit >= 0xd800 && unit <= 0xdbff) {
      if (index + 1 >= value.length) {
        throw FormatException('$context contains malformed UTF-16');
      }
      final low = value.codeUnitAt(index + 1);
      if (low < 0xdc00 || low > 0xdfff) {
        throw FormatException('$context contains malformed UTF-16');
      }
      index++;
      width = 4;
    } else if (unit >= 0xdc00 && unit <= 0xdfff) {
      throw FormatException('$context contains malformed UTF-16');
    } else {
      width = 3;
    }
    length += width;
    if (length > maxBytes) {
      throw FormatException('$context exceeds its $maxBytes-byte limit');
    }
  }
  return length;
}
