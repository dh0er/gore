/// Immutable identity projected from one newly-created empty revision-3 project.
final class Revision3ProjectBootstrapIdentity {
  const Revision3ProjectBootstrapIdentity._({
    required this.projectId,
    required this.revision,
    required this.name,
    required this.version,
    required this.author,
    required this.authoringLocales,
  });

  final String projectId;
  final int revision;
  final String name;
  final String version;
  final String author;
  final List<String> authoringLocales;
}

/// Exact executable-generation facts copied from the trusted Story catalog.
final class Revision3ProjectBootstrapTarget {
  const Revision3ProjectBootstrapTarget._({
    required this.edition,
    required this.executableByteLength,
    required this.executableSha256,
  });

  final String edition;
  final int executableByteLength;
  final String executableSha256;
}

/// Canonical empty managed-project document plus facts a creator must verify
/// after the managed store reopens it.
///
/// This helper is filesystem-free. It does not build, deploy, or runtime-qualify
/// the project.
final class Revision3ProjectBootstrap {
  const Revision3ProjectBootstrap._({
    required this.canonicalProjectJson,
    required this.identity,
    required this.target,
  });

  static const int format = 2;
  static const int schemaRevision = 3;
  static const int initialRevision = 0;
  static const int maxNameUtf8Bytes = 256;
  static const int maxVersionUtf8Bytes = 128;
  static const int maxAuthorUtf8Bytes = 256;
  static const int maxAuthoringLocales = 64;

  /// Creates one deterministic, byte-canonical empty revision-3 document.
  ///
  /// [projectId] must already have been generated by a cryptographically secure
  /// caller. This boundary verifies only its canonical non-zero 128-bit shape.
  factory Revision3ProjectBootstrap.create({
    required AuthoringStoryCatalogGeneration generation,
    required String projectId,
    required String name,
    required String version,
    required String author,
    Iterable<String> authoringLocales = const <String>[],
  }) {
    _requireProjectId(projectId);
    _requireMetadata(name, maxNameUtf8Bytes, 'project name');
    _requireMetadata(version, maxVersionUtf8Bytes, 'project version');
    _requireMetadata(author, maxAuthorUtf8Bytes, 'project author');
    final locales = _canonicalLocales(authoringLocales);
    final target = _validatedTarget(generation);
    final identity = Revision3ProjectBootstrapIdentity._(
      projectId: projectId,
      revision: initialRevision,
      name: name,
      version: version,
      author: author,
      authoringLocales: locales,
    );
    final canonicalProjectJson = jsonEncode(<String, Object?>{
      'format': format,
      'schema_revision': schemaRevision,
      'project_id': identity.projectId,
      'revision': identity.revision,
      'meta': <String, Object?>{
        'name': identity.name,
        'version': identity.version,
        'author': identity.author,
      },
      'target': <String, Object?>{
        'executable': <String, Object?>{
          'byte_len': target.executableByteLength,
          'sha256': target.executableSha256,
        },
      },
      'authoring_locales': identity.authoringLocales,
      'entities': <String, Object?>{},
      'asset_store': <String, Object?>{'assets': <String, Object?>{}},
    });
    return Revision3ProjectBootstrap._(
      canonicalProjectJson: canonicalProjectJson,
      identity: identity,
      target: target,
    );
  }

  final String canonicalProjectJson;
  final Revision3ProjectBootstrapIdentity identity;
  final Revision3ProjectBootstrapTarget target;
}

