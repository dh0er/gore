use anyhow::{Context, Result};
use std::{fs, path::PathBuf};

use crate::cmd::validate_mod_name;

pub fn run(mod_name: String, mods_dir: PathBuf) -> Result<()> {
    validate_mod_name(&mod_name)
        .with_context(|| format!("invalid mod name '{mod_name}'"))?;
    let mod_dir = mods_dir.join(&mod_name);
    let scripts_dir = mod_dir.join("Scripts");
    fs::create_dir_all(&scripts_dir)
        .with_context(|| format!("creating '{}'", scripts_dir.display()))?;

    // enabled.txt — UE4SS requires this file to load the mod
    fs::write(mod_dir.join("enabled.txt"), "")
        .context("writing enabled.txt")?;

    // main.lua — template with CDO pattern
    let main_lua = format!(
        r#"-- {name} — generated by gore-cli scaffold
-- Edit this file to apply CDO overrides at game load.
--
-- Example pattern (proven working):
--   local cdo = StaticFindObject("/Script/Angelscript.Default__ItFo_Apple")
--   if cdo and cdo:IsValid() then
--     local before = cdo.m_Value
--     cdo.m_Value = 500
--     print(string.format("[{name}] ItFo_Apple.m_Value %s -> %s\n",
--       tostring(before), tostring(cdo.m_Value)))
--   end
--
-- Use `gore-cli stubs` to generate LuaLS type stubs for autocomplete.
-- Require stubs: (add to your .luarc.json: {{ "workspace.library": ["path/to/stubs"] }})

-- gore-lua helper loader (require + robust loadfile fallback)
local ok, gore = pcall(require, "gore-lua")
if not ok then gore = nil end -- a failed pcall leaves the error string in `gore`; clear it
if not gore then
    local f = loadfile("ue4ss/Mods/shared/gore-lua/gore-lua.lua")
    if f then
        -- run the chunk under pcall: a load-time error in the SDK must not abort the mod
        local ok2, res = pcall(f)
        gore = ok2 and res or nil
    end
end
-- use gore.* helpers below; call gore.help.list() or see lua/README.md

local function apply()
  -- TODO: add your CDO overrides here
end

apply()
"#,
        name = mod_name
    );
    fs::write(scripts_dir.join("main.lua"), main_lua)
        .context("writing main.lua")?;

    println!("Created mod scaffold -> {}", mod_dir.display());
    Ok(())
}
