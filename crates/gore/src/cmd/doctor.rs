//! `gore doctor` — one read-only pass over the setup that says what is installed and what is
//! wrong with it.
//!
//! # Why this exists
//!
//! Every other command in this CLI answers a question about the one thing it was pointed at.
//! Nothing answered "what is my setup". A tester who built a working item override, deployed it,
//! and then saw nothing in the game had to open PowerShell and walk the install by hand before he
//! found the cause — UE4SS was not installed. No command would have told him: `gore mod deploy`
//! creates `ue4ss\Mods\` itself when it is missing, so a deploy that reports success proves the
//! files were written and nothing else. His verdict on the toolkit was "for building, yes; for
//! repairing, no", and that is the gap this command closes.
//!
//! # Reuse, not a second opinion
//!
//! Every check here answers with the same helper the command it diagnoses uses: the game root
//! through [`gore_loc::config::game_root`] (so the reported root is the one every other command
//! resolves), the install layout through [`gore_mod::resolve_game_paths`], the `~mods` folder
//! through [`gore_tex::container::mods_dir`], the deployment through
//! [`gore_mod::mgr::status::status`] (what `gore mgr status` prints), the install-mutation lock
//! and gore-as recovery artifacts through [`gore_as::compile::probe_install_compile_state`] (what
//! deploy and `as compile` consult before they refuse), and the localized-text catalog through
//! [`gore_loc::loc_store::status`] (what `gore loc status` prints). A doctor that disagreed with
//! the commands it diagnoses would be worse than no doctor at all.
//!
//! Nothing in this module writes, creates, or removes anything.

