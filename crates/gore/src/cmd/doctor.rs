    /// `extracted_at` comes from the source file rather than staying at zero, because that is
    /// the order reality has: `gore loc extract` reads a cache that already exists, so the file
    /// it read is never newer than the extraction. A fixture stuck at the epoch makes every file
    /// look rewritten since, which is the opposite of the fresh case these tests describe.
    /// A shared catalog that exists, for the checks that are about how well it matches the install
    /// rather than about whether it is there.
    fn extracted_catalog(dir: &Path) -> PathBuf {
        let path = dir.join("loc_catalog.json");
        std::fs::write(&path, br#"{"itfo_apple":{"german":"Apfel"}}"#).unwrap();
        path
    }

    fn meta(source: &Path, bytes: u64) -> LocMeta {
        // One second AFTER the cache was last written, which is what extracting from an installed
        // file looks like. Equal timestamps are the ambiguous case, not the healthy one, and a
        // fixture that used them stood in for a state the tests were not about.
        let extracted_at = std::fs::metadata(source)
            .and_then(|m| m.modified())
            .ok()
            .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
            .map(|since| since.as_secs() + 1)
            .unwrap_or(0);
        LocMeta {
            source_path: source.display().to_string(),
            source_bytes: bytes,
            id_count: 43851,
            languages: vec!["german".into(), "english".into()],
            extracted_at,
            // The ladder below is what a catalog without this field falls back to, and these
            // fixtures are what keeps that path covered. The recorded-identity path has its own.
            source_modified_nanos: None,
            catalog_path: r"C:\Users\x\AppData\Local\gore\loc_catalog.json".into(),
        }
    }

    /// The same fixture, but recording the source's own modification time the way `extract` does
    /// now — which is what a catalog written by a current build carries.
    fn meta_with_identity(source: &Path, bytes: u64) -> LocMeta {
        let nanos = std::fs::metadata(source)
            .and_then(|m| m.modified())
            .ok()
            .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
            .and_then(|since| u64::try_from(since.as_nanos()).ok());
        LocMeta { source_modified_nanos: nanos, ..meta(source, bytes) }
    }

