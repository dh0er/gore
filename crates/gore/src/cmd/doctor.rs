/// Width of the verdict column; `problem` is the longest word plus one space.
const VERDICT_WIDTH: usize = 8;
/// Width of the check-title column.
const TITLE_WIDTH: usize = 14;

/// How many names an enumerating check PRINTS before it says how many more there are. A doctor
/// that dumps 300 pak files at someone is a doctor nobody reads to the end of.
///
/// Applied at print time only: `--json` carries every item, because a cap is a decision about a
/// person's screen and an "… and 10 more" string is not something a caller can parse.
const MAX_LISTED: usize = 12;

/// First line of every `main.lua` [`gore_modgen::gen::gen_lua`] writes, and therefore the only
/// evidence on disk that a UE4SS mod folder holds GORE-generated overrides rather than somebody
/// else's Lua. Matched as a prefix, stopping before the em dash, so the marker stays ASCII.
/// `gen_lua_still_writes_the_marker_this_module_looks_for` pins it to the generator.
const GENERATED_MARKER: &str = "-- Generated by gore-cli";

/// How much of a `main.lua` is read to look for [`GENERATED_MARKER`]. A mod folder can hold
/// anything, and this check is a diagnosis, not a reason to pull an arbitrary file into memory.
const MARKER_PROBE_BYTES: usize = 128;

/// What one check found, ordered from "nothing to do" to "this is the fault".
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
enum Verdict {
    /// Checked, and there is nothing to do about it.
    Ok,
    /// True and worth knowing, but not a fault: the game left running, a mod that is merely
    /// disabled, a catalog extracted from another install.
    Note,
    /// A reason a mod would silently do nothing, or a mess somebody has to clean up.
    Problem,
    /// Not answerable, because something this check reads is not there. Always accompanied by the
    /// check that reported the missing thing.
    Skipped,
}

impl Verdict {
    fn label(self) -> &'static str {
        match self {
            Verdict::Ok => "ok",
            Verdict::Note => "note",
            Verdict::Problem => "problem",
            Verdict::Skipped => "skipped",
        }
    }
}

/// One line of the report: what was looked at, what was found, and — when something is wrong —
/// what to do about it.
#[derive(Serialize)]
struct Check {
    /// Stable key for `--json`. Never renamed once shipped: a caller greps for it.
    id: &'static str,
    /// Column heading in the human report.
    title: &'static str,
    verdict: Verdict,
    /// One line, the finding itself.
    detail: String,
    /// Enumerated evidence (mod folders, leftover files), printed indented under `detail`.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    items: Vec<String>,
    /// What to do next. Present exactly when the verdict is not `ok`, so a reader can act on the
    /// report without leaving it to look a command up.
    #[serde(skip_serializing_if = "Option::is_none")]
    fix: Option<String>,
}

impl Check {
    fn new(id: &'static str, title: &'static str, verdict: Verdict, detail: impl Into<String>) -> Self {
        Self {
            id,
            title,
            verdict,
            detail: detail.into(),
            items: Vec::new(),
            fix: None,
        }
    }

    fn with_items(mut self, items: Vec<String>) -> Self {
        self.items = items;
        self
    }

    fn with_fix(mut self, fix: impl Into<String>) -> Self {
        self.fix = Some(fix.into());
        self
    }
}

/// The whole report. The counts are at the top level so a `--json` caller can gate on them without
/// walking `checks`.
#[derive(Serialize)]
struct Report {
    /// Resolved install root, absent when nothing resolved.
    #[serde(skip_serializing_if = "Option::is_none")]
    game_root: Option<String>,
    /// Where that root came from: `--game`, `config`, or `auto-detect`.
    game_source: &'static str,
    ok: usize,
    note: usize,
    problem: usize,
    skipped: usize,
    checks: Vec<Check>,
}

impl Report {
    fn new(game_root: Option<&Path>, game_source: &'static str, checks: Vec<Check>) -> Self {
        let count = |want: Verdict| checks.iter().filter(|c| c.verdict == want).count();
        Self {
            game_root: game_root.map(|p| p.display().to_string()),
            game_source,
            ok: count(Verdict::Ok),
            note: count(Verdict::Note),
            problem: count(Verdict::Problem),
            skipped: count(Verdict::Skipped),
            checks,
        }
    }
}

/// `gore doctor` exits 0 whenever it produced a report, however bad the news in it.
///
/// The alternative — non-zero as soon as any check is a problem — was rejected because of who runs
/// this command. It is reached by somebody whose mod did nothing, often through a wrapper, a GUI,
/// or an agent that reads a non-zero exit as "the command failed". Conflating "the doctor found
/// that UE4SS is missing" with "the doctor could not run" is precisely the confusion this command
/// exists to remove, and it would also make `gore doctor` fail on a perfectly healthy day, because
/// a game left running is worth a line and is not a fault. A caller that wants to gate on the
/// findings reads `--json`: every check carries its own verdict and the top level carries the
/// counts. The one non-zero exit is a doctor that could not write its own report.
pub fn run(game: Option<PathBuf>, json: bool) -> Result<()> {
    let report = collect(game.as_deref());
    if json {
        println!("{}", serde_json::to_string_pretty(&report)?);
    } else {
        print_report(&report);
    }
    Ok(())
}

/// Run every check. Ordered the way somebody debugs: where is the game, is it the right game, can
/// anything run a mod at all, what is deployed, what is left over, what is in the way.
fn collect(explicit: Option<&Path>) -> Report {
    let cfg = gore_loc::config::load();
    let source = game_path_source(explicit.is_some(), cfg.game_path.as_deref());
    let resolved = gore_loc::config::game_root(explicit.map(Path::to_path_buf)).ok();

    let mut checks = vec![check_game_path(explicit, cfg.game_path.as_deref(), resolved.as_deref())];

    // A root that resolved to nothing on disk is no more inspectable than one that did not
    // resolve, and running the rest against it would restate the same single cause as four more
    // problems — burying the one line that says what to fix.
    let looked = match resolved.as_deref() {
        Some(root) => present(root),
        None => Ok(None),
    };
    let readable = match looked {
        Ok(Some(metadata)) if metadata.is_dir() => resolved,
        Ok(_) => None,
        Err(error) => {
            // There and unreadable, which is neither of the above. Skipping as "no install to look
            // at" described an install that is not there, and sent people to reconfigure a path
            // that was right all along.
            for (id, title) in SKIPPED_WITHOUT_INSTALL {
                checks.push(
                    Check::new(id, title, Verdict::Skipped, format!("could not be read: {error}"))
                        .with_fix(
                            "run the same command from a shell that can read the install",
                        ),
                );
            }
            return Report::new(None, source, checks);
        }
    };
    let Some(root) = readable else {
        // Every remaining check reads the install. Say so once per check rather than dropping
        // them: a report that silently shrinks looks like a report that found less to say.
        for (id, title) in SKIPPED_WITHOUT_INSTALL {
            checks.push(Check::new(
                id,
                title,
                Verdict::Skipped,
                "no install to look at",
            ));
        }
        return Report::new(None, source, checks);
    };

    let gp = gore_mod::resolve_game_paths(&root);
    // One probe answers two checks — the running game and the leftover locks/journals — and
    // enumerating the process list twice could disagree with itself between the two lines.
    let probe = gore_as::compile::probe_install_compile_state(&gp.root);
    // Unreadable counts as present: `check_deployment` reads the same file and reports the
    // failure itself, and the only other consumer uses this to decide whether `*.gore-bak` files
    // are orphans. Guessing "no deployment" there would turn one unreadable file into a claim that
    // game files are still modified.
    let record_present = match present(&gore_mod::deploy_record_path(&gp.root)) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_file()),
        Err(_) => true,
    };

    checks.push(check_install(&gp));
    checks.push(check_ue4ss(&gp));
    checks.push(check_ue4ss_mods(&gp));
    checks.push(check_deployment(
        &gp,
        &gore_mod::mgr::paths::library_dir(),
        &gore_mod::mgr::paths::loadout_path(),
    ));
    checks.push(check_mods_folder(&gp));
    checks.push(check_leftovers(&gp, &probe, record_present));
    checks.push(check_game_process(&probe));
    checks.push(check_loc_catalog(
        gore_loc::loc_store::status(),
        &gore_loc::paths::loc_catalog_path(),
        gp.lcache.as_deref(),
    ));

    Report::new(Some(&gp.root), source, checks)
}

/// The checks that cannot run without a resolved install, in report order. Kept next to `collect`
/// so a check added below is either listed here or is a check that never reads the game.
const SKIPPED_WITHOUT_INSTALL: &[(&str, &str)] = &[
    ("install", "install"),
    ("ue4ss", "UE4SS"),
    ("ue4ss_mods", "UE4SS mods"),
    ("deployment", "deployment"),
    ("mods_folder", "~mods"),
    ("leftovers", "leftovers"),
    ("game_process", "game process"),
    ("loc_catalog", "loc catalog"),
];

/// Where the resolved game root came from, in `gore config list`'s own words plus the one source
/// that command cannot have (an explicit `--game`).
///
/// Pure, and deliberately a copy of nothing: both this and `config list` treat a blank or
/// whitespace-only `game_path` as unset because [`gore_loc::config::game_root`] does, so a config
/// file holding `""` is reported as auto-detected rather than as configured. A doctor that named a
/// different source than `gore config list` would send someone to edit the wrong thing.
fn game_path_source(explicit: bool, configured: Option<&str>) -> &'static str {
    if explicit {
        "--game"
    } else if configured.is_some_and(|value| !value.trim().is_empty()) {
        "config"
    } else {
        "auto-detect"
    }
}

fn check_game_path(
    explicit: Option<&Path>,
    configured: Option<&str>,
    resolved: Option<&Path>,
) -> Check {
    let mut items = vec![format!(
        "config file: {}",
        gore_loc::config::config_path().display()
    )];
    if let Some(value) = configured {
        items.push(format!("game-path = {value}"));
    }
    let source = game_path_source(explicit.is_some(), configured);

    let Some(root) = resolved else {
        return Check::new(
            "game_path",
            "game path",
            Verdict::Problem,
            "no game path set, and no Steam install was auto-detected",
        )
        .with_items(items)
        .with_fix(
            "run 'gore config detect' to find a Steam install, or \
             'gore config set game-path <path>' to name it yourself",
        );
    };

    match present(root) {
        Ok(Some(metadata)) if metadata.is_dir() => {}
        Ok(_) => {
            return Check::new(
                "game_path",
                "game path",
                Verdict::Problem,
                format!("{} (source: {source}) does not exist", root.display()),
            )
            .with_items(items)
            .with_fix(
                "the path resolved but there is no directory there — the game moved, or the \
                 drive is not mounted. Set it again with 'gore config set game-path <path>'",
            );
        }
        // The configured path is right and something is stopping this process from reading it.
        // Telling somebody their install does not exist is the one answer that makes them break a
        // working configuration trying to fix it.
        Err(error) => {
            return Check::new(
                "game_path",
                "game path",
                Verdict::Problem,
                format!("{} (source: {source}) could not be read: {error}", root.display()),
            )
            .with_items(items)
            .with_fix(
                "the path is set correctly. Run the same command from a shell that can read the \
                 install, or check the folder's permissions — do not change the configured path",
            );
        }
    }

    Check::new(
        "game_path",
        "game path",
        Verdict::Ok,
        format!("{} (source: {source})", root.display()),
    )
    .with_items(items)
}

/// Does the resolved root actually hold a Gothic 1 Remake install?
///
/// The four entries below are the ones the rest of the toolkit resolves against: the shipping
/// executable, the pak folder that carries `~mods`, the localization cache folder, and the script
/// folder. `resolve_game_paths` builds all of them off `<root>\G1R`, so this joins the same child
/// rather than counting ancestors off one of its fields.
fn check_install(gp: &GamePaths) -> Check {
    let g1r = gp.root.join("G1R");
    let required: [(&str, PathBuf, bool); 4] = [
        (
            r"G1R\Binaries\Win64\G1R-Win64-Shipping.exe",
            gp.executable.clone(),
            false,
        ),
        (r"G1R\Content\Paks", g1r.join("Content").join("Paks"), true),
        (r"G1R\Story\Cache", g1r.join("Story").join("Cache"), true),
        (r"G1R\Script", g1r.join("Script"), true),
    ];

    let mut missing: Vec<String> = Vec::new();
    let mut unreadable: Vec<String> = Vec::new();
    for (label, path, want_dir) in &required {
        match present(path) {
            Ok(Some(metadata)) if metadata.is_dir() == *want_dir => {}
            Ok(_) => missing.push((*label).to_string()),
            Err(error) => unreadable.push(format!("{label}: {error}")),
        }
    }

    // An entry that could not be inspected is not an entry that is gone, and the two fixes below —
    // repoint the config, verify the game files — are both wrong for it. Neither should be printed
    // for a folder that is sitting right there behind an ACL.
    if !unreadable.is_empty() {
        return Check::new(
            "install",
            "install",
            Verdict::Problem,
            format!(
                "{} of the {} entries that identify the install could not be inspected",
                unreadable.len(),
                required.len()
            ),
        )
        .with_items(unreadable)
        .with_fix(
            "nothing here says the install is wrong, only that it could not be looked at. Run \
             the same command from a shell that can read it",
        );
    }

    if missing.is_empty() {
        return Check::new(
            "install",
            "install",
            Verdict::Ok,
            "looks like Gothic 1 Remake (executable, Paks, Story\\Cache and Script all present)",
        );
    }

    // The executable is the one entry whose absence means "this is not the game"; the others can
    // be missing from a partial or verifying install, which is a different sentence.
    let exe_missing = missing.iter().any(|m| m.ends_with(".exe"));
    let detail = if exe_missing {
        format!(
            "does not look like a Gothic 1 Remake install (missing: {})",
            missing.join(", ")
        )
    } else {
        format!("install is incomplete (missing: {})", missing.join(", "))
    };
    Check::new("install", "install", Verdict::Problem, detail).with_fix(if exe_missing {
        "point GORE at the folder that CONTAINS G1R\\, not at G1R\\ itself or a Steam library: \
         'gore config set game-path <path>' (or 'gore config detect')"
    } else {
        "verify the game files in Steam; commands that read these folders will fail until they \
         are back"
    })
}

/// `<install>\G1R\Binaries\Win64\ue4ss` and its parts.
///
/// This is the check the whole command was written for. Item and stat overrides are Lua that only
/// UE4SS runs, GORE does not install it, and `gore mod deploy` creates the `Mods\` directory
/// itself — so the presence of `Mods\` proves a deploy happened, never that anything will load
/// what it put there.
fn check_ue4ss(gp: &GamePaths) -> Check {
    let ue4ss = ue4ss_dir(gp);
    let dll = ue4ss.join("UE4SS.dll");
    let mods = &gp.ue4ss_mods;

    // Every verdict below turns on whether one of three paths is there. `Path::is_dir()` answers
    // `false` when it could not tell, and each of the sentences underneath would then be a
    // confident account of an install this process never managed to read.
    let unreadable = |error: String| {
        Check::new(
            "ue4ss",
            "UE4SS",
            Verdict::Problem,
            format!("UE4SS could not be inspected: {error}"),
        )
        .with_fix("run the same command from a shell that can read the install")
    };
    let ue4ss_present = match present(&ue4ss) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_dir()),
        Err(error) => return unreadable(error),
    };
    let dll_present = match present(&dll) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_file()),
        Err(error) => return unreadable(error),
    };
    let mods_present = match present(mods) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_dir()),
        Err(error) => return unreadable(error),
    };
    // UE4SS.dll is the payload; something has to load it. The game imports a proxy DLL, and the one
    // this toolkit knows is `dwmapi.dll` beside the executable — `gore-as` moves that exact file
    // aside for a regen, so its name is not a guess. Without it the payload sits there unloaded and
    // every deployed override does nothing, which is the symptom this check exists to name.
    let proxy = ue4ss.parent().map(|win64| win64.join("dwmapi.dll"));
    let proxy_present = match proxy.as_deref().map(present) {
        Some(Ok(metadata)) => metadata.is_some_and(|metadata| metadata.is_file()),
        Some(Err(error)) => return unreadable(error),
        // No parent directory to look in. Not a shape this check can judge, and not one it should
        // invent a finding about.
        None => true,
    };

    if !ue4ss_present {
        return Check::new(
            "ue4ss",
            "UE4SS",
            Verdict::Problem,
            format!("not installed: there is no {}", ue4ss.display()),
        )
        .with_fix(
            "item and stat overrides are Lua, and UE4SS is the loader that runs it — without it a \
             deployed override mod sits in the install doing nothing and no command reports a \
             problem. Install UE4SS into that folder; GORE does not ship or install it. See the \
             UE4SS section of docs\\guide\\getting-started.md",
        );
    }

    if !dll_present {
        // The folder without the DLL is the shape `gore mod deploy` leaves behind on an install
        // that never had UE4SS: it creates ue4ss\Mods\ to put the mod in, and nothing else.
        return Check::new(
            "ue4ss",
            "UE4SS",
            Verdict::Problem,
            format!(
                "{} exists but has no UE4SS.dll, so nothing loads the mods in it",
                ue4ss.display()
            ),
        )
        .with_items(vec![format!(
            "Mods\\: {}",
            if mods_present {
                "present (a gore deploy creates it, so this proves nothing about UE4SS)"
            } else {
                "not there"
            }
            .to_string()
        )])
        .with_fix(
            "install UE4SS into that folder (UE4SS.dll, UE4SS-settings.ini and Mods\\ sit beside \
             each other). See the UE4SS section of docs\\guide\\getting-started.md",
        );
    }

    let mut items = vec![format!("UE4SS.dll: {}", dll.display())];
    let settings = ue4ss.join("UE4SS-settings.ini");
    match present(&settings) {
        Ok(Some(metadata)) if metadata.is_file() => {}
        Ok(_) => items.push("UE4SS-settings.ini: not there".to_string()),
        Err(error) => items.push(format!("UE4SS-settings.ini: {error}")),
    }
    let log = ue4ss.join("UE4SS.log");
    let log_present = match present(&log) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_file()),
        Err(error) => {
            items.push(format!("UE4SS.log: {error}"));
            false
        }
    };
    if log_present {
        // The only machine-readable evidence that an override actually applied, and the first
        // thing to read when a mod is deployed and the game shows nothing.
        items.push(format!("UE4SS.log: {}", log.display()));
    }

    if !mods_present {
        return Check::new(
            "ue4ss",
            "UE4SS",
            Verdict::Note,
            format!("installed, but there is no {} yet", mods.display()),
        )
        .with_items(items)
        .with_fix("'gore mod deploy' and 'gore gen -o <mods dir>' both create it");
    }

    if !proxy_present {
        // A Note, not a Problem: UE4SS supports several proxy names and somebody may have installed
        // it under one this toolkit does not look for. Saying so is still worth a line, because the
        // alternative is a report that calls UE4SS installed while nothing loads it.
        return Check::new(
            "ue4ss",
            "UE4SS",
            Verdict::Note,
            format!(
                "installed at {}, but there is no dwmapi.dll next to the game executable to load \
                 it",
                ue4ss.display()
            ),
        )
        .with_items(items)
        .with_fix(
            "UE4SS is loaded by a proxy DLL the game imports, and dwmapi.dll is the one this \
             toolkit knows — it belongs in G1R\\Binaries\\Win64. If you installed UE4SS under a \
             different proxy name this line is nothing to act on; otherwise nothing loads UE4SS \
             and every deployed override does nothing. See the UE4SS section of \
             docs\\guide\\getting-started.md",
        );
    }

    Check::new(
        "ue4ss",
        "UE4SS",
        Verdict::Ok,
        format!("installed at {}", ue4ss.display()),
    )
    .with_items(items)
}

/// One UE4SS mod folder as this report sees it.
struct Ue4ssMod {
    name: String,
    /// UE4SS loads a folder because an `enabled.txt` sits in it; that empty file is the switch.
    enabled: bool,
    /// Its `Scripts\main.lua` starts with [`GENERATED_MARKER`], so GORE wrote it.
    generated: bool,
}

/// What is in `ue4ss\Mods\`, and which of it will run.
///
/// The case worth catching here happened during the blind tests: a mod folder left enabled from an
/// earlier session competes with the new one for the same class default. Both apply, the later
/// loader wins, nothing anywhere says so, and the value in the game is the one nobody asked for.
/// Only GORE-generated folders are counted for that warning — UE4SS ships enabled mods of its own,
/// and warning about those would fire on every healthy install.
fn check_ue4ss_mods(gp: &GamePaths) -> Check {
    let mods = &gp.ue4ss_mods;
    let mods_present = match present(mods) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_dir()),
        // Reported rather than skipped: "no Mods folder" is the answer that hides the competing
        // override this check exists to find.
        Err(error) => {
            return Check::new(
                "ue4ss_mods",
                "UE4SS mods",
                Verdict::Problem,
                format!("could not inspect the UE4SS mod folder: {error}"),
            )
            .with_fix("run the same command from a shell that can read the install")
        }
    };
    if !mods_present {
        return Check::new(
            "ue4ss_mods",
            "UE4SS mods",
            Verdict::Skipped,
            format!("no {}", mods.display()),
        );
    }

    // A folder that exists and cannot be read is reported as unread. "No mod folders" is the answer
    // that hides a competing override mod, which is the thing this check is for.
    let found = match read_ue4ss_mods(mods) {
        Ok(found) => found,
        Err(error) => {
            return Check::new(
                "ue4ss_mods",
                "UE4SS mods",
                Verdict::Problem,
                format!("could not inspect the UE4SS mod folder: {error}"),
            )
            .with_fix("run the same command from a shell that can read the install")
        }
    };
    if found.is_empty() {
        return Check::new(
            "ue4ss_mods",
            "UE4SS mods",
            Verdict::Ok,
            "no mod folders in ue4ss\\Mods",
        );
    }

    let enabled = found.iter().filter(|m| m.enabled).count();
    let items = found
        .iter()
        .map(|m| {
            format!(
                "{} [{}]{}",
                m.name,
                if m.enabled { "enabled" } else { "disabled" },
                if m.generated { " gore override" } else { "" }
            )
        })
        .collect();

    let competing: Vec<&Ue4ssMod> = found
        .iter()
        .filter(|m| m.enabled && m.generated)
        .collect();
    let detail = format!("{} mod folder(s), {enabled} enabled", found.len());

    if competing.len() > 1 {
        let names: Vec<&str> = competing.iter().map(|m| m.name.as_str()).collect();
        return Check::new("ue4ss_mods", "UE4SS mods", Verdict::Problem, detail)
            .with_items(items)
            .with_fix(format!(
                "{} GORE-generated override mods are enabled at once ({}). If two of them set the \
                 same class default, the one UE4SS loads last wins and neither the log nor the \
                 game says which. Delete the folder you are not using, or delete its enabled.txt",
                competing.len(),
                names.join(", ")
            ));
    }

    // A GORE-generated override with no `enabled.txt` is not loaded by UE4SS, and its overrides
    // therefore do nothing — which is precisely the "I deployed it and the game is unchanged" this
    // report gets read to explain. A Note and not a Problem: deleting that file is also how the
    // branch above tells people to settle a conflict, so being disabled is a legitimate state. What
    // was missing is that the consequence was visible nowhere but in a bracket inside `items`.
    let dormant: Vec<&str> = found
        .iter()
        .filter(|m| m.generated && !m.enabled)
        .map(|m| m.name.as_str())
        .collect();
    if !dormant.is_empty() {
        return Check::new("ue4ss_mods", "UE4SS mods", Verdict::Note, detail)
            .with_items(items)
            .with_fix(format!(
                "{} GORE-generated override mod(s) have no enabled.txt, so UE4SS skips them and                  the class defaults they set are never applied ({}). If you disabled them on                  purpose there is nothing to do; otherwise put an empty enabled.txt back in the                  folder, or deploy the bundle again — it carries one",
                dormant.len(),
                dormant.join(", ")
            ));
    }

    Check::new("ue4ss_mods", "UE4SS mods", Verdict::Ok, detail).with_items(items)
}

/// Directories under `Mods\`, sorted, with `shared` left out: that is the gore-lua SDK namespace
/// `gore deploy-shared` installs for other mods to `require`, not a mod, and it has no enabled.txt
/// by design.
///
/// A directory that cannot be read is reported rather than counted as empty. "No mod folders" is
/// exactly the answer that hides a competing override mod, and this check exists to find those.
/// `fs::metadata`, with "not there" separated from "could not tell".
///
/// `Path::is_dir()` and `Path::is_file()` answer `false` for both, and every check in this module
/// that asked them was therefore able to report a clean install it had not managed to look at. Four
/// separate places had that bug; they now share this one, which returns `Ok(None)` only for a real
/// absence and the reason for anything else. Links are followed, as the `is_*` calls did.
fn present(path: &Path) -> Result<Option<std::fs::Metadata>, String> {
    match std::fs::metadata(path) {
        Ok(metadata) => Ok(Some(metadata)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(format!("{} could not be read: {error}", path.display())),
    }
}

fn read_ue4ss_mods(mods: &Path) -> Result<Vec<Ue4ssMod>, String> {
    let entries = std::fs::read_dir(mods)
        .map_err(|error| format!("{} could not be read: {error}", mods.display()))?;
    let entries = entries
        .collect::<std::io::Result<Vec<_>>>()
        .map_err(|error| format!("{} could not be read: {error}", mods.display()))?;
    let mut found: Vec<Ue4ssMod> = Vec::new();
    for entry in entries {
        let dir = entry.path();
        match present(&dir)? {
            Some(metadata) if metadata.is_dir() => {}
            // A plain file, or something that vanished between the listing and the look.
            _ => continue,
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.eq_ignore_ascii_case("shared") {
            continue;
        }
        found.push(Ue4ssMod {
            // An `enabled.txt` that cannot be read is not an absent one. Since a generated override
            // without it is now reported as doing nothing, guessing here would invent that finding.
            enabled: present(&dir.join("enabled.txt"))?.is_some_and(|m| m.is_file()),
            // Propagated rather than defaulted: a marker that cannot be read is not a mod that
            // carries no overrides, and treating it as one is how a competing generated override
            // would disappear from a report whose whole job is to find it.
            generated: is_generated_override_mod(&dir)?,
            name,
        });
    }
    // Enabled first, then by name. A UE4SS install carries a couple of dozen folders and the
    // listing is capped, so plain alphabetical order would spend the whole cap on the disabled
    // stock mods and cut off the handful that actually run — which is the only part anyone asked
    // about.
    found.sort_by_key(|m| (!m.enabled, m.name.to_lowercase()));
    Ok(found)
}

/// Was this mod folder's `Scripts\main.lua` written by `gore gen` / `gore mod build`?
/// `Ok(false)` means the file was read and carries no marker. `Err` means it could not be read,
/// which is not the same answer: reporting it as "not generated" is how two competing generated
/// overrides and one unreadable marker came back as a clean verdict.
fn is_generated_override_mod(dir: &Path) -> Result<bool, String> {
    use std::io::Read;
    let marker = dir.join("Scripts").join("main.lua");
    let mut file = match std::fs::File::open(&marker) {
        Ok(file) => file,
        // No `main.lua` at all is a real answer: this folder holds no generated overrides.
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(format!("{} could not be read: {error}", marker.display())),
    };
    let mut head = [0u8; MARKER_PROBE_BYTES];
    let read = file
        .read(&mut head)
        .map_err(|error| format!("{} could not be read: {error}", marker.display()))?;
    Ok(String::from_utf8_lossy(&head[..read]).starts_with(GENERATED_MARKER))
}

/// What can still be said about a deployment when the manager's loadout will not parse.
///
/// The first three rungs of the status ladder — nothing deployed, an interrupted apply, a
/// standalone `gore mod deploy` bundle — are read off the deploy record before the target loadout
/// is consulted at all. Returning on the loadout error therefore hid a half-finished deploy, and an
/// active bundle, behind a complaint about an unrelated JSON file. Those two are the report's whole
/// reason for existing; the loadout is what `gore mgr` needs, and it is said alongside.
///
/// Anything past those three rungs genuinely is a diff against the loadout, so it is not attempted.
fn deployment_without_a_loadout(
    gp: &GamePaths,
    library: &Path,
    items: Vec<String>,
    loadout_path: &Path,
    error: impl std::fmt::Display,
) -> Check {
    let broken = format!(
        "the manager loadout could not be read: {error}. Delete or repair {} — every 'gore mgr' \
         command reads it first",
        loadout_path.display()
    );
    // An empty target is safe for exactly the record-only rungs, and its answer is ignored for
    // every other one.
    let record_only = gore_mod::mgr::status::status(&gp.root, library, &Default::default());
    match record_only {
        Ok(ManagerStatus::RecoveryRequired) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            "a previous deploy was interrupted and the install is half-changed",
        )
        .with_items(items)
        .with_fix(format!(
            "run 'gore mgr reset' (or 'gore mod undeploy') to restore the game before deploying \
             anything else. Separately: {broken}"
        )),
        Ok(ManagerStatus::StudioDeployActive { mod_name }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            format!("one bundle is deployed: {mod_name}; the manager loadout is unreadable"),
        )
        .with_items(items)
        .with_fix(broken),
        // Rung 4, and the ladder's own words for it are "stale regardless of the loadout" — it is
        // decided by verifying the recorded files, not by any diff against a target. It is also
        // literally the case this whole report exists for: deploy said yes and the game shows
        // nothing. Losing it behind a complaint about a JSON file was the worst of the three.
        Ok(ManagerStatus::GameUpdated { drifted }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            format!(
                "{} deployed file(s) were changed outside GORE — a Steam update or an integrity \
                 verify has put the game's own version back",
                drifted.len()
            ),
        )
        .with_items(drifted)
        .with_fix(format!(
            "this is the case where the tool reported success and the game shows nothing. Run \
             'gore mgr apply' (or re-deploy the bundle) to rebuild against the refreshed files. \
             Separately: {broken}"
        )),
        // Two failures, and the deploy record is the one that stops things working. Reporting only
        // the loadout named the lesser of them and left the other out of the report entirely.
        Err(error) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            format!("the deploy record could not be read: {error}"),
        )
        .with_items(items)
        .with_fix(format!("{broken}. The deploy record is the more urgent of the two")),
        // What is left is `NothingDeployed`, `InSync` and `ChangesPending`. The last two ARE the
        // diff against the loadout that could not be read, so there is nothing to say about them.
        Ok(_) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            "the manager loadout could not be read",
        )
        .with_items(items)
        .with_fix(broken),
    }
}

/// Is anything deployed, and is it still what was deployed?
///
/// This is `gore mgr status`, called the same way with the same shared library and loadout, so the
/// two never say different things about the same install. It reads and hashes the files the record
/// claims, which is why it is the slowest line in the report — and why it can report the case a
/// bare "a record exists" could not: a Steam update or integrity verify that quietly put the
/// pristine file back underneath a deployment that still looks active.
fn check_deployment(gp: &GamePaths, library: &Path, loadout_path: &Path) -> Check {
    let record = gore_mod::deploy_record_path(&gp.root);
    let items = vec![
        format!("record:  {}", record.display()),
        format!("library: {}", library.display()),
        format!("loadout: {}", loadout_path.display()),
    ];

    let target = match gore_mod::mgr::loadout::load(loadout_path) {
        Ok(loadout) => loadout,
        Err(error) => return deployment_without_a_loadout(gp, library, items, loadout_path, error),
    };

    match gore_mod::mgr::status::status(&gp.root, library, &target) {
        Ok(ManagerStatus::NothingDeployed) => Check::new(
            "deployment",
            "deployment",
            Verdict::Ok,
            "nothing is deployed (no deploy record in the install)",
        )
        .with_items(items),
        Ok(ManagerStatus::StudioDeployActive { mod_name }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Ok,
            format!("one bundle is deployed: {mod_name}"),
        )
        .with_items(items),
        Ok(ManagerStatus::InSync { loadout }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Ok,
            format!(
                "the manager loadout is deployed and in sync ({} mod(s))",
                loadout.len()
            ),
        )
        .with_items(items),
        Ok(ManagerStatus::ChangesPending { deployed, target }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Note,
            format!(
                "{} mod(s) are deployed but the loadout now names {} — the game does not have \
                 your latest change",
                deployed.len(),
                target.len()
            ),
        )
        .with_items(items)
        .with_fix("run 'gore mgr apply' to put the current loadout into the game"),
        Ok(ManagerStatus::GameUpdated { drifted }) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            format!(
                "{} deployed file(s) were changed outside GORE — a Steam update or an integrity \
                 verify has put the game's own version back",
                drifted.len()
            ),
        )
        .with_items(drifted.clone())
        .with_fix(
            "this is the case where the tool reported success and the game shows nothing. Run \
             'gore mgr apply' (or re-deploy the bundle) to rebuild against the refreshed files",
        ),
        Ok(ManagerStatus::RecoveryRequired) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            "a previous deploy was interrupted and the install is half-changed",
        )
        .with_items(items)
        .with_fix(
            "run 'gore mgr reset' (or 'gore mod undeploy') to restore the game before deploying \
             anything else",
        ),
        Err(error) => Check::new(
            "deployment",
            "deployment",
            Verdict::Problem,
            format!("the deploy record could not be read: {error}"),
        )
        .with_items(items),
    }
}

/// What is mounted from the game's additive override folder.
///
/// Texture and DataAsset mods leave a Zen triplet here instead of patching a game file, so this is
/// the only place they are visible, and a triplet from a deployment that was undeployed by hand
/// would still be mounted.
fn check_mods_folder(gp: &GamePaths) -> Check {
    let dir = gore_tex::container::mods_dir(&gp.root);
    let dir_present = match present(&dir) {
        Ok(metadata) => metadata.is_some_and(|metadata| metadata.is_dir()),
        Err(error) => {
            return Check::new(
                "mods_folder",
                "~mods",
                Verdict::Problem,
                format!("could not inspect the additive mod folder: {error}"),
            )
            .with_fix("run the same command from a shell that can read the install")
        }
    };
    if !dir_present {
        return Check::new(
            "mods_folder",
            "~mods",
            Verdict::Ok,
            format!("no {} (nothing additive is mounted)", dir.display()),
        );
    }
    let mut names = match file_names(&dir) {
        Ok(names) => names,
        Err(error) => {
            return Check::new(
                "mods_folder",
                "~mods",
                Verdict::Problem,
                format!("could not inspect the additive mod folder: {error}"),
            )
        }
    };
    names.sort_by_key(|name| name.to_lowercase());
    if names.is_empty() {
        return Check::new(
            "mods_folder",
            "~mods",
            Verdict::Ok,
            format!("{} is empty", dir.display()),
        );
    }
    Check::new(
        "mods_folder",
        "~mods",
        Verdict::Ok,
        format!("{} file(s) mounted from {}", names.len(), dir.display()),
    )
    .with_items(names)
}

/// Things in the install that should not still be there.
///
/// Two sources, because they are left by two different kinds of interruption: the install-mutation
/// lock, the gore-as compile lock, its recovery journal and its cache/JIT/proxy backups come from
/// [`gore_as::compile::probe_install_compile_state`] — the same probe deploy and `as compile`
/// consult before they refuse to start — and the `*.gore-bak` snapshots come from a scan of the
/// four folders this toolkit edits in place. A `*.gore-bak` is normal while something is deployed;
/// with no deploy record it means a game file is still modified and its pristine copy is sitting
/// next to it, which is exactly the state "I undeployed and the game still looks wrong" describes.
fn check_leftovers(
    gp: &GamePaths,
    probe: &InstallCompileStateProbe,
    record_present: bool,
) -> Check {
    let mut items: Vec<String> = probe
        .artifacts
        .iter()
        .map(|artifact| format!("{:?}: {}", artifact.kind, artifact.path))
        .collect();
    let artifact_count = items.len();

    // Same posture as the probe's own InspectionFailed below: a directory that cannot be read is
    // reported as unread, never as clean. This check exists to find leftovers, so answering "none"
    // because the scan failed is the one wrong answer it can give.
    //
    // A failed scan is an ADDITIONAL finding, not a replacement for the one ranked above it.
    // Returning here dropped the lock/recovery verdict — the only thing this check reports that
    // actually stops deploy — and sent the reader off to fix read permissions while the blocker
    // itself stayed put and unmentioned.
    let (backups, scan_error) = match find_backups(gp) {
        Ok(backups) => (backups, None),
        Err(error) => (Vec::new(), Some(error)),
    };
    let orphan_backups = !record_present && !backups.is_empty();
    items.extend(backups.iter().cloned());
    if let Some(error) = &scan_error {
        items.push(format!("could not scan for leftover backups: {error}"));
    }

    // Ranked ahead of both inspection failures below. A lock or journal is why deploy and
    // 'as compile' refuse to start, and its recovery action is to finish the open transaction, not
    // to re-run with more rights. Inside the probe `InspectionFailed` already outranks
    // `RecoveryArtifactsPresent` — an unreadable process list is enough to trigger it — so unless
    // this branch comes first, a found lock is reported as a Note about something else entirely.
    if artifact_count > 0 {
        let partly_unread = scan_error.is_some()
            || probe.disposition == InstallCompileStateDisposition::InspectionFailed;
        let and_unread = if partly_unread {
            ", and part of the install could not be read, so there may be more"
        } else {
            ""
        };
        return Check::new(
            "leftovers",
            "leftovers",
            Verdict::Problem,
            format!(
                "{artifact_count} lock/recovery artifact(s) are still in the install, so deploy \
                 and 'as compile' will refuse to start{and_unread}"
            ),
        )
        .with_items(items)
        .with_fix(
            "a GORE process was interrupted. Make sure none is running, then run \
             'gore mod undeploy' (or 'gore mgr reset') to finish the transaction it left open",
        );
    }

    if let Some(error) = scan_error {
        return Check::new(
            "leftovers",
            "leftovers",
            Verdict::Problem,
            format!("could not scan for leftover backups: {error}"),
        )
        .with_items(items)
        .with_fix("run the same command from a shell that can read the install");
    }

    if probe.disposition == InstallCompileStateDisposition::InspectionFailed {
        // The probe fails closed; say which part it could not read rather than reporting a clean
        // install it never managed to look at.
        let why = probe
            .issues
            .first()
            .map(|issue| issue.message.clone())
            .unwrap_or_else(|| "the probe did not say".into());
        return Check::new(
            "leftovers",
            "leftovers",
            Verdict::Note,
            format!("the install could not be inspected in full: {why}"),
        )
        .with_items(items)
        .with_fix("run the same command from a shell that can read the install");
    }

    // `artifact_count` is 0 from here: the branch above returned on every other value.
    if backups.is_empty() {
        return Check::new(
            "leftovers",
            "leftovers",
            Verdict::Ok,
            "no locks, journals or leftover backups in the install",
        );
    }

    if orphan_backups {
        return Check::new(
            "leftovers",
            "leftovers",
            Verdict::Note,
            format!(
                "{} *.gore-bak backup(s) with no deployment to belong to — a game file is \
                 probably still modified",
                backups.len()
            ),
        )
        .with_items(items)
        .with_fix(
            "these are the pristine bytes of files edited in place. Restore a bank with \
             'gore audio restore --bank <bank>', or re-run 'gore mod undeploy' if a deployment \
             was removed by hand",
        );
    }

    Check::new(
        "leftovers",
        "leftovers",
        Verdict::Ok,
        format!(
            "{} *.gore-bak backup(s), which is what an active deployment looks like",
            backups.len()
        ),
    )
    .with_items(items)
}

/// Is the game open right now?
fn check_game_process(probe: &InstallCompileStateProbe) -> Check {
    match probe.game_process {
        InstallCompileGameProcessDisposition::NotRunning => Check::new(
            "game_process",
            "game process",
            Verdict::Ok,
            "G1R-Win64-Shipping.exe is not running",
        ),
        InstallCompileGameProcessDisposition::Running => Check::new(
            "game_process",
            "game process",
            Verdict::Note,
            "G1R-Win64-Shipping.exe is running",
        )
        .with_fix(
            "deploy, undeploy and 'as compile' refuse to change an installation while the game \
             holds it open. Close the game before any of them",
        ),
        InstallCompileGameProcessDisposition::InspectionFailed => Check::new(
            "game_process",
            "game process",
            Verdict::Note,
            "could not tell whether the game is running",
        )
        .with_fix(
            "deploy and undeploy fail closed on this too, so they will refuse until the process \
             list can be read",
        ),
    }
}

/// What the installed cache's modification time says about the extraction that recorded it.
///
/// `SameSecond` is its own answer rather than part of `Untouched`. `extracted_at` is whole seconds
/// (`now_unix`), so nothing finer survives to compare against — and `gore loc extract` followed
/// straight away by `gore loc import` lands inside one second routinely. Folding it into "not newer
/// than the extraction" reported a rewritten cache as healthy.
enum Written {
    AfterExtraction,
    SameSecond,
    Untouched,
    NoTimestamp,
}

/// Does the shared localized-text catalog still describe the installed `.lcache`?
///
/// `gore loc status` reports the source path and size the catalog was extracted from, and that can
/// disagree with the cache in the install — most often because `gore loc import` re-encrypted the
/// cache afterwards, which changes its size. Nothing breaks, but every tool that turns a text id
/// into text is then reading the text the game no longer has, which reads exactly like an edit
/// that did not take.
fn check_loc_catalog(meta: Option<LocMeta>, catalog: &Path, installed: Option<&Path>) -> Check {
    let Some(meta) = meta else {
        // `status()` reads `loc_meta.json` only, and returns `None` for a missing, unreadable or
        // malformed sidecar alike. `extract` DELETES that sidecar when it cannot write it, on
        // purpose, rather than leave one describing the previous extraction — so "no metadata" is
        // a state a successful extraction can leave behind, with the catalog itself in place and
        // perfectly usable by `gore find`, Mod Studio and the save editor.
        return match present(catalog) {
            Ok(Some(metadata)) if metadata.is_file() => Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Note,
                "a localized-text catalog is there, but nothing records where it came from",
            )
            .with_items(vec![format!("catalog: {}", catalog.display())])
            .with_fix(
                "the catalog is usable as it is. Its provenance sidecar (loc_meta.json) is \
                 missing or unreadable, which is what 'gore loc extract' leaves behind when it \
                 could not write one — re-run it to restore the record of which install this \
                 came from",
            ),
            Ok(_) => Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Note,
                "no localized-text catalog has been extracted",
            )
            .with_fix(
                "run 'gore loc extract' — the save editor, Mod Studio and 'gore loc' all read \
                 that one shared catalog",
            ),
            Err(error) => Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Problem,
                format!("the localized-text catalog could not be inspected: {error}"),
            )
            .with_fix("run the same command from a shell that can read it"),
        };
    };

    // The metadata survives independently of the file it describes: deleting `loc_catalog.json`
    // and leaving `loc_meta.json` reported a healthy catalog, complete with an id count, for
    // something `gore find`, Mod Studio and the save editor can no longer load. Everything below
    // this point is about how well the catalog matches the install, which is not a question worth
    // answering about a catalog that is not there.
    match present(catalog) {
        Ok(Some(metadata)) if metadata.is_file() => {}
        Ok(_) => {
            return Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Problem,
                "the record of an extracted catalog is there, but the catalog itself is gone",
            )
            .with_items(vec![format!("expected at: {}", catalog.display())])
            .with_fix(
                "run 'gore loc extract' — every tool that turns a text id into text reads that \
                 one file, and until it is back they all fall back to showing raw ids",
            );
        }
        Err(error) => {
            return Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Problem,
                format!("the localized-text catalog could not be inspected: {error}"),
            )
            .with_items(vec![format!("expected at: {}", catalog.display())])
            .with_fix("run the same command from a shell that can read it");
        }
    }

    let summary = format!(
        "{} ids in {} language(s)",
        meta.id_count,
        meta.languages.len()
    );
    let items = vec![
        format!("catalog: {}", meta.catalog_path),
        format!("source:  {} ({} bytes)", meta.source_path, meta.source_bytes),
    ];

    let Some(installed) = installed else {
        return Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Note,
            format!("{summary}, but this install has no AlkimiaLocalization .lcache to compare it against"),
        )
        .with_items(items);
    };

    // `gore loc extract --lcache some\\path.lcache` records the spelling it was given, and this
    // process resolved `installed` to an absolute path — so a relative recording never matched and
    // every such catalog was reported as belonging to another install. Resolved against the current
    // directory first, which is a guess: it was recorded relative to wherever `extract` ran. A
    // mismatch on a relative spelling is therefore reported as not knowing, never as another
    // install.
    let recorded = Path::new(&meta.source_path);
    let resolved = match std::env::current_dir() {
        Ok(cwd) => cwd.join(recorded),
        Err(_) => recorded.to_path_buf(),
    };
    if !same_path(&resolved, installed) && recorded.is_relative() {
        return Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Note,
            format!(
                "{summary}, and whether it came from this install cannot be told: the catalog \
                 records its source as a relative path"
            ),
        )
        .with_items(
            items
                .into_iter()
                .chain([format!("installed: {}", installed.display())])
                .collect(),
        )
        .with_fix(
            "run 'gore loc extract' from this install, or pass an absolute --lcache path, so the \
             catalog records which file it came from",
        );
    }

    if !same_path(&resolved, installed) {
        return Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Note,
            format!("{summary}, extracted from a different file than this install's cache"),
        )
        .with_items(
            items
                .into_iter()
                .chain([format!("installed: {}", installed.display())])
                .collect(),
        )
        .with_fix(
            "the catalog describes another install. Run 'gore loc extract' to re-extract from the \
             one you are pointed at",
        );
    }

    // Length alone cannot prove currency: `gore loc import` re-encrypts in place, and replacing a
    // string with one that encodes to the same number of bytes leaves the file exactly as long as
    // it was. The catalog carries no content hash to compare against — adding one would change the
    // shared format that Mod Studio and the save editor also read — so the modification time is the
    // second signal, and an unchanged length with an untouched mtime is reported as what it is:
    // nothing that looks changed, rather than proof of a match.
    // Four answers, not two. Length cannot separate an untouched cache from a same-length
    // rewrite, so this is the only signal there is — and both ways it can fail to give one have to
    // stay distinguishable from "unchanged", which is the reassuring direction.
    let written = |m: &std::fs::Metadata| -> Written {
        let Ok(modified) = m.modified() else {
            return Written::NoTimestamp;
        };
        let Ok(since) = modified.duration_since(std::time::UNIX_EPOCH) else {
            return Written::NoTimestamp;
        };
        let seconds = since.as_secs();
        if seconds > meta.extracted_at {
            Written::AfterExtraction
        } else if seconds == meta.extracted_at {
            Written::SameSecond
        } else {
            Written::Untouched
        }
    };

    let inconclusive = |why: &str| {
        Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Note,
            format!(
                "{summary}; the installed cache is the same length, and whether it has been \
                 rewritten since cannot be told — {why}"
            ),
        )
        .with_items(items.clone())
        .with_fix(
            "nothing here says the catalog is stale. If text in the game disagrees with what \
             'gore loc' shows, run 'gore loc extract' to settle it",
        )
    };

    // The catalog can now record the source's own modification time, which answers "is this still
    // the file it was built from" directly — no second-resolution ladder, and none of its blind
    // spots. Catalogs written before that field existed fall back to the ladder below.
    let modified_nanos = |m: &std::fs::Metadata| -> Option<u64> {
        m.modified()
            .ok()?
            .duration_since(std::time::UNIX_EPOCH)
            .ok()
            .and_then(|since| u64::try_from(since.as_nanos()).ok())
    };

    match std::fs::metadata(installed) {
        Ok(m) if m.len() == meta.source_bytes && meta.source_modified_nanos.is_some() => {
            match (modified_nanos(&m), meta.source_modified_nanos) {
                (Some(now), Some(recorded)) if now == recorded => Check::new(
                    "loc_catalog",
                    "loc catalog",
                    Verdict::Ok,
                    format!("{summary}; the installed cache is the file it was extracted from"),
                )
                .with_items(items),
                (Some(_), _) => Check::new(
                    "loc_catalog",
                    "loc catalog",
                    Verdict::Problem,
                    format!(
                        "{summary}, but the installed cache has been written since the \
                         extraction — it is the same length, so what changed is its contents"
                    ),
                )
                .with_items(items)
                .with_fix(
                    "'gore loc import' re-encrypts the cache in place and can leave its length \
                     unchanged. Run 'gore loc extract' so the shared catalog describes the text \
                     that is installed",
                ),
                (None, _) => inconclusive("this filesystem reported no modification time"),
            }
        }
        Ok(m) if m.len() == meta.source_bytes => match written(&m) {
            Written::AfterExtraction => Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Problem,
                format!(
                    "{summary}, but the installed cache has been written since the extraction — \
                     it is the same length, so what changed is its contents"
                ),
            )
            .with_items(items)
            .with_fix(
                "'gore loc import' re-encrypts the cache in place and can leave its length \
                 unchanged. Run 'gore loc extract' so the shared catalog describes the text that \
                 is installed",
            ),
            Written::NoTimestamp => {
                inconclusive("this filesystem reported no modification time")
            }
            Written::SameSecond => inconclusive(
                "it was last written in the same second the extraction recorded, and the record \
                 keeps whole seconds only",
            ),
            Written::Untouched => Check::new(
                "loc_catalog",
                "loc catalog",
                Verdict::Ok,
                format!("{summary}; the installed cache is unchanged in size and mtime since then"),
            )
            .with_items(items),
        },
        Ok(m) => {
            let live = m.len();
            Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Problem,
            format!(
                "{summary}, but stale: extracted from {} bytes and the installed cache is now \
                 {live}",
                meta.source_bytes
            ),
        )
        .with_items(items)
        .with_fix(
            "the cache changed after the extraction — 'gore loc import' re-encrypts it in place, \
             and a game update replaces it. Run 'gore loc extract' so the shared catalog describes \
             the file that is actually installed",
        )
        }
        Err(error) => Check::new(
            "loc_catalog",
            "loc catalog",
            Verdict::Note,
            format!("{summary}, but the installed cache could not be read: {error}"),
        )
        .with_items(items),
    }
}

/// `resolve_game_paths` always builds `…\Binaries\Win64\ue4ss\Mods`, so the parent is the `ue4ss`
/// folder. The fallback keeps this total instead of panicking on a shape that cannot occur.
fn ue4ss_dir(gp: &GamePaths) -> PathBuf {
    gp.ue4ss_mods
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| gp.ue4ss_mods.clone())
}

/// The four folders this toolkit edits a game file in place in, each of which leaves the pristine
/// bytes in a `<file>.gore-bak` sibling: the localization cache, the FMOD banks, the voice-over
/// archives and the AngelScript cache. Scanning these rather than the whole install keeps the
/// check cheap, and a `.gore-bak` anywhere else was not written by this CLI.
fn find_backups(gp: &GamePaths) -> Result<Vec<String>, String> {
    let g1r = gp.root.join("G1R");
    let dirs = [
        g1r.join("Story").join("Cache"),
        gp.fmod_desktop.clone(),
        gp.voice_over.clone(),
        g1r.join("Script"),
    ];
    let mut found: Vec<String> = Vec::new();
    for dir in &dirs {
        for name in file_names(dir)? {
            if name.ends_with(".gore-bak") {
                found.push(dir.join(name).display().to_string());
            }
        }
    }
    found.sort();
    Ok(found)
}

/// Plain file names directly in `dir`.
///
/// A directory that is not there has no files, and that is an answer. A directory that is there and
/// cannot be read is not an answer, and used to be reported as one: swallowing the error returned an
/// empty vector, which `~mods` read as "empty" and the backup scan read as "nothing left over". A
/// doctor that says `ok` because it could not look is worse than one that says nothing, and the
/// installs where this happens — permissions, a half-mounted drive, I/O errors — are exactly the
/// ones it exists for. Per-entry failures count the same way; a directory half-read is not a
/// directory read.
fn file_names(dir: &Path) -> Result<Vec<String>, String> {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(format!("{} could not be read: {error}", dir.display())),
    };
    let mut names = Vec::new();
    for entry in entries {
        let entry = entry
            .map_err(|error| format!("{} could not be read: {error}", dir.display()))?;
        if present(&entry.path())?.is_some_and(|metadata| metadata.is_file()) {
            names.push(entry.file_name().to_string_lossy().into_owned());
        }
    }
    Ok(names)
}


/// Windows path identity is case-insensitive, which is the same reason `semantic_install_root`
/// compares its `G1R` component with `eq_ignore_ascii_case`. Not canonicalized: that would
/// introduce the `\\?\` verbatim prefix the rest of the toolkit avoids, and it requires the file to
/// still exist, which is not something this comparison should depend on.
///
/// Compared by component rather than as one string. `gore loc extract --lcache C:/Games/G1R/...`
/// records forward slashes, `resolve_game_paths` builds the same path with backslashes, and a
/// single `eq_ignore_ascii_case` over the whole thing then called two spellings of one file two
/// different installs. `Path::components` splits on either separator on Windows, and drops `.`
/// components on the way through.
///
/// `..` is left in place. Resolving it lexically is wrong wherever a symlink or a junction is
/// involved, and a path that needs it compares unequal — the safe direction for a check whose only
/// output is a note telling somebody to re-extract.
fn same_path(a: &Path, b: &Path) -> bool {
    let parts = |path: &Path| -> Vec<String> {
        path.components()
            .filter(|component| !matches!(component, std::path::Component::CurDir))
            .map(|component| component.as_os_str().to_string_lossy().to_lowercase())
            .collect()
    };
    parts(a) == parts(b)
}

fn print_report(report: &Report) {
    for check in &report.checks {
        println!(
            "{:<VERDICT_WIDTH$}{:<TITLE_WIDTH$}{}",
            check.verdict.label(),
            check.title,
            check.detail
        );
        let indent = " ".repeat(VERDICT_WIDTH + TITLE_WIDTH);
        for item in check.items.iter().take(MAX_LISTED) {
            println!("{indent}{item}");
        }
        // The same marker `location list` appends to a clipped listing, so one learned habit
        // covers both. `--json` is not clipped; this is a decision about a screen.
        if check.items.len() > MAX_LISTED {
            println!("{indent}… and {} more", check.items.len() - MAX_LISTED);
        }
        if let Some(fix) = &check.fix {
            println!("{indent}fix: {fix}");
        }
    }
    println!();
    println!(
        "{} check(s): {} ok, {} note, {} problem, {} skipped",
        report.checks.len(),
        report.ok,
        report.note,
        report.problem,
        report.skipped
    );
}

