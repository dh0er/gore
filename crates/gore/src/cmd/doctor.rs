    /// Write a UE4SS mod folder; `generated` decides whether its main.lua carries the marker.
    fn make_mod(mods: &Path, name: &str, enabled: bool, generated: bool) {
        let dir = mods.join(name);
        std::fs::create_dir_all(dir.join("Scripts")).unwrap();
        if enabled {
            std::fs::write(dir.join("enabled.txt"), b"").unwrap();
        }
        let lua = if generated {
            gen_lua(&OverridesConfig {
                meta: MetaConfig {
                    name: name.to_string(),
                    delay_ms: 0,
                },
                overrides: vec![SingleOverride {
                    module: "Angelscript".into(),
                    class: "ItFo_Apple".into(),
                    field: "m_Value".into(),
                    value: OverrideValue::Int(500),
                }],
            })
        } else {
            "-- hand written\n".to_string()
        };
        std::fs::write(dir.join("Scripts").join("main.lua"), lua).unwrap();
    }

